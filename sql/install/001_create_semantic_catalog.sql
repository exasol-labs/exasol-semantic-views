WHERE NOT EXISTS (
  SELECT 1 FROM SYS_SEMANTIC.ATTRIBUTE_BINDINGS ab
  WHERE ab.ATTRIBUTE_TYPE = 'DIMENSION' AND ab.ATTRIBUTE_ID = d.DIMENSION_ID
);

