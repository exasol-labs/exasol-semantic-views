-- ============================================================================
-- Declared foreign keys
-- ============================================================================
--
-- Every join between two catalog tables is now declared as a real FOREIGN KEY
-- constraint rather than living only in the compiler's queries. An agent (or a
-- BI tool, or a person with a fresh psql-shaped mental model) that finds
-- SYS_SEMANTIC and asks "how do these 42 tables connect?" gets the answer from
-- the standard system views instead of reverse-engineering it from Lua:
--
--   SELECT CONSTRAINT_TABLE, COLUMN_NAME, REFERENCED_TABLE, REFERENCED_COLUMN
--   FROM EXA_ALL_CONSTRAINT_COLUMNS
--   WHERE CONSTRAINT_SCHEMA = 'SYS_SEMANTIC' AND CONSTRAINT_TYPE = 'FOREIGN KEY'
--   ORDER BY CONSTRAINT_TABLE, ORDINAL_POSITION;
--
-- SEMANTIC_CATALOG.CATALOG_RELATIONSHIPS wraps that query, adds the view
-- surfaces (which cannot carry constraints) and the discriminated references
-- below, and hands back a ready-to-paste ON clause.
--
-- Every constraint is created DISABLE, deliberately. DISABLE in Exasol means
-- "declared but not enforced": the constraint is fully visible in
-- EXA_ALL_CONSTRAINTS and EXA_ALL_CONSTRAINT_COLUMNS -- which is the whole
-- point, since discoverability is what was missing -- while write semantics
-- stay exactly as they were. Enforcing them would be a different and much
-- larger change, and not a safe one to fold in here:
--
--   * MODELS.ACTIVE_VERSION_ID and MODEL_VERSIONS.MODEL_ID reference each
--     other, so no insert order satisfies both under enforcement.
--   * The catalog soft-deletes via STATUS columns and keeps run/log history
--     (QUERY_LOG, AGENT_REQUEST_LOG, VALIDATION_RUNS) whose parents can be
--     legitimately dropped and rebuilt by a re-publish.
--   * An ENABLE constraint is validated against existing rows on creation, so
--     any deployment carrying a historical orphan would fail to upgrade.
--     A DISABLE constraint installs over existing data unconditionally.
--
-- The DROP CONSTRAINT IF EXISTS before each ADD keeps this section idempotent:
-- 001 runs with CREATE TABLE IF NOT EXISTS, so a re-install over an existing
-- catalog reaches these statements with the tables (and possibly the previous
-- constraints) already in place, and Exasol rejects a duplicate constraint
-- name. Re-running the file therefore re-asserts the current FK map rather
-- than failing or silently skipping tables it did not just create.

