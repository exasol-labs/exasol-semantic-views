-- compilation did not consult them. Two nouns and two foreign keys in a catalog
-- a user browses, standing for behaviour that does not exist. Dropped rather
-- than kept as a promise; if the feature arrives it can declare its own tables.
-- DROP is idempotent and the tables were always empty, so an upgrade loses
-- nothing.
DROP TABLE IF EXISTS SYS_SEMANTIC.CALCULATION_ITEMS CASCADE;
