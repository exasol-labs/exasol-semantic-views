  RUNTIME_CHECKSUM   VARCHAR(64) NOT NULL,
  INSTALLED_AT       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  INSTALLED_BY       VARCHAR(256) DEFAULT CURRENT_USER NOT NULL
);

