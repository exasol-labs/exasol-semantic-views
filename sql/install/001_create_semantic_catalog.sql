-- ── Discriminated (polymorphic) references ───────────────────────────────────
--
-- These columns are foreign keys in every sense except the one SQL can
-- express: the table they point at is chosen at runtime by a sibling
-- discriminator column, so no single REFERENCES clause is correct and Exasol
-- cannot declare the constraint. Left undocumented they are the worst case for
-- an exploring agent -- a bare DECIMAL that looks unrelated to anything -- so
-- each one is described here instead. Column comments surface automatically in
-- SEMANTIC_CATALOG.CATALOG_COLUMNS.DESCRIPTION and in the DISCRIMINATED rows of
-- SEMANTIC_CATALOG.CATALOG_RELATIONSHIPS, so this text is reachable by query
-- and not only by reading this file.

