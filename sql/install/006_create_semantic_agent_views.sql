-- The compile result contract, as data.
--
-- COMPILE_REQUEST_JSON, COMPILE_SQL, and COMPILE_SQL_DEBUG each return nine
-- columns. A consumer that reads them positionally has to know two things that
-- are easy to get wrong, and that a documentation error already got wrong once
-- (see docs/known-issues.md): ORIGINAL_SQL is present but always NULL for the
-- JSON entrypoint, and the ninth column is AGENT_REQUEST_ID for two of the
-- scripts but QUERY_LOG_ID for the debug variant.
--
-- The first eight columns are shared by construction here, so the three
-- layouts cannot drift apart in this view; tests/integration/verify_catalog_introspection.py
-- asserts every row against the live result set of each script.
CREATE OR REPLACE VIEW SEMANTIC_AGENT.COMPILE_RESULT_SCHEMA_FOR_AGENT AS
WITH ENTRYPOINTS AS (
  SELECT
    'COMPILE_REQUEST_JSON' AS SCRIPT_NAME,
    'AGENT_REQUEST_ID' AS HANDLE_COLUMN,
    'AGENT_REQUEST' AS HANDLE_TYPE,
    FALSE AS ECHOES_ORIGINAL_SQL,
    -- Result column names differ by lane, and a consumer that switches lanes
    -- loses every lookup by name unless it is told.
    CAST('Its result columns are named after the canonical field ("total_revenue"), '
      || 'or after the synonym as written when the request used one.'
      AS VARCHAR(300)) AS OUTPUT_NAMING
  UNION ALL
  SELECT 'COMPILE_SQL', 'AGENT_REQUEST_ID', 'AGENT_REQUEST', TRUE,
    'Its result columns are named as SQL names them: an alias as written, '
      || 'anything else upper-cased: TOTAL_REVENUE.'
  UNION ALL
  SELECT 'COMPILE_SQL_DEBUG', 'QUERY_LOG_ID', 'QUERY_LOG', TRUE,
    'Its result columns are named as SQL names them: an alias as written, '
      || 'anything else upper-cased: TOTAL_REVENUE.'
),
LAYOUT AS (
  SELECT
    1 AS ORDINAL_POSITION,
    'STATUS' AS COLUMN_NAME,
    CAST('VARCHAR(32)' AS VARCHAR(30)) AS DATA_TYPE,
    CAST('OK, ERROR, NEEDS_CLARIFICATION' AS VARCHAR(200)) AS ALLOWED_VALUES,
    CAST('Never NULL.' AS VARCHAR(200)) AS NULL_WHEN,
    CAST('Compile outcome. Check this before reading any other column.'
      AS VARCHAR(500)) AS DESCRIPTION
  UNION ALL
  SELECT 2, 'ERROR_CODE', 'VARCHAR(128)', NULL, 'NULL when STATUS is OK.',
    'Stable SEMANTIC_REQUEST_* or SEMANTIC_QUERY_* code for a refusal.'
  UNION ALL
  SELECT 3, 'ERROR_MESSAGE', 'VARCHAR(2000000)', NULL, 'NULL when STATUS is OK.',
    'Human-readable refusal text naming the blocking object where one applies.'
  UNION ALL
  SELECT 4, 'ORIGINAL_SQL', 'VARCHAR(2000000)', NULL,
    'NULL unless the entrypoint takes Semantic SQL.',
    'The request as submitted, echoed back for logging and diffing.'
  UNION ALL
  SELECT 5, 'GENERATED_SQL', 'VARCHAR(2000000)', NULL,
    'NULL when STATUS is not OK.',
    'Executable physical SQL. This is the column to run.'
  UNION ALL
  SELECT 6, 'PLAN_JSON', 'VARCHAR(2000000)', NULL,
    'NULL when compilation stopped before planning.',
    'Plan provenance: relationship paths, proofs, representations, '
      || 'materialization decisions, and warnings.'
  UNION ALL
  SELECT 7, 'CLARIFICATION_JSON', 'VARCHAR(2000000)', NULL,
    'NULL unless STATUS is NEEDS_CLARIFICATION.',
    'Candidate fields and the question to ask when a request is ambiguous.'
  UNION ALL
  SELECT 8, 'VALIDATION_RUN_ID', 'DECIMAL(18,0)', NULL,
    'NULL when no validation run gated the request.',
    'The validation run the compile was proven against.'
)
SELECT
  e.SCRIPT_NAME,
  l.ORDINAL_POSITION,
  l.ORDINAL_POSITION - 1 AS ZERO_BASED_INDEX,
  l.COLUMN_NAME,
  l.DATA_TYPE,
  l.ALLOWED_VALUES,
  CASE
    WHEN l.COLUMN_NAME = 'ORIGINAL_SQL' AND NOT e.ECHOES_ORIGINAL_SQL
      THEN 'Always NULL for this script; the column is still present, so '
        || 'positional indices line up with the other entrypoints.'
    ELSE l.NULL_WHEN
  END AS NULL_WHEN,
  CASE
    WHEN l.COLUMN_NAME = 'GENERATED_SQL' THEN l.DESCRIPTION || ' ' || e.OUTPUT_NAMING
    ELSE l.DESCRIPTION
  END AS DESCRIPTION
FROM ENTRYPOINTS e
CROSS JOIN LAYOUT l
UNION ALL
SELECT
  e.SCRIPT_NAME,
  9,
  8,
  e.HANDLE_COLUMN,
  'DECIMAL(18,0)',
  NULL,
  'NULL when the request was not logged.',
  'Handle for EXPLAIN_COMPILED_SQL and RECORD_AGENT_FEEDBACK, with handle type '
    || e.HANDLE_TYPE || '. The ninth column differs by entrypoint.'
FROM ENTRYPOINTS e;

-- What fusion is in play, as data.
--
-- Fusion changes the answer -- a partitioned entity merges aggregate states
-- across sources, a reconciled attribute takes its value from the authoritative
-- one -- and none of it was visible on the agent surface. An agent reading only
-- FIELDS_FOR_AGENT could not tell a single-source column from a reconciled one,
-- and had no way to explain the number it reported.
--
-- One row per fusion declaration, keyed by entity: representations and their
-- partition coverage, authority roles, attribute policies, and certified
-- identity mappings. FUSION_ASPECT says which kind of declaration a row is.
CREATE OR REPLACE VIEW SEMANTIC_AGENT.FUSION_FOR_AGENT AS
SELECT
  er.MODEL_ID,
  er.MODEL_NAME,
  er.VERSION_ID,
  er.ENTITY_ID,
  er.ENTITY_NAME,
  CASE WHEN er.COVERAGE_PREDICATE IS NULL THEN 'REPRESENTATION' ELSE 'PARTITION' END
    AS FUSION_ASPECT,
  er.REPRESENTATION_NAME,
  CAST(NULL AS VARCHAR(32)) AS ATTRIBUTE_TYPE,
  CAST(NULL AS VARCHAR(256)) AS ATTRIBUTE_NAME,
  CASE WHEN er.COVERAGE_PREDICATE IS NULL THEN er.REPRESENTATION_ROLE ELSE 'UNION' END
    AS STRATEGY,
  er.COVERAGE_PREDICATE,
  er.VALID_FROM,
  er.VALID_TO,
  er.SOURCE_SCHEMA || '.' || er.SOURCE_OBJECT AS SOURCE_OBJECT
FROM SEMANTIC_CATALOG.ENTITY_REPRESENTATIONS er
WHERE er.STATUS = 'ACTIVE'
UNION ALL
SELECT
  ra.MODEL_ID,
  ra.MODEL_NAME,
  ra.VERSION_ID,
  ra.ENTITY_ID,
  ra.ENTITY_NAME,
  'AUTHORITY' AS FUSION_ASPECT,
  ra.REPRESENTATION_NAME,
  NULL,
  NULL,
  ra.AUTHORITY_ROLE AS STRATEGY,
  NULL,
  NULL,
  NULL,
  NULL
FROM SEMANTIC_CATALOG.REPRESENTATION_AUTHORITIES ra
WHERE ra.STATUS = 'ACTIVE'
UNION ALL
SELECT
  afp.MODEL_ID,
  afp.MODEL_NAME,
  afp.VERSION_ID,
  afp.ENTITY_ID,
  afp.ENTITY_NAME,
  'ATTRIBUTE_POLICY' AS FUSION_ASPECT,
  NULL,
  afp.ATTRIBUTE_TYPE,
  afp.ATTRIBUTE_NAME,
  afp.FUSION_STRATEGY AS STRATEGY,
  NULL,
  NULL,
  NULL,
  NULL
FROM SEMANTIC_CATALOG.ATTRIBUTE_FUSION_POLICIES afp
WHERE afp.STATUS = 'ACTIVE'
UNION ALL
SELECT
  imr.MODEL_ID,
  imr.MODEL_NAME,
  imr.VERSION_ID,
  imr.ENTITY_ID,
  imr.ENTITY_NAME,
  'IDENTITY' AS FUSION_ASPECT,
  imr.REPRESENTATION_NAME,
  'IDENTITY',
  imr.IDENTITY_NAME,
  imr.CERTIFICATION_STATUS AS STRATEGY,
  NULL,
  NULL,
  NULL,
  imr.SOURCE_SCHEMA || '.' || imr.SOURCE_OBJECT AS SOURCE_OBJECT
FROM SEMANTIC_CATALOG.IDENTITY_MAPPING_RELATIONS imr
WHERE imr.STATUS = 'ACTIVE';

