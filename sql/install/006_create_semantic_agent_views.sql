-- Which deployment am I actually attached to?
--
-- Exasol Personal reassigns a deployment's port on every start, so a client
-- pinned to a static DSN can silently reach a *different* database and answer
-- confidently from the wrong catalog. Nothing on the agent surface let a caller
-- notice. This is the assertable identity: the database plus the installed
-- build, which together are unique per deployment.
CREATE OR REPLACE VIEW SEMANTIC_AGENT.DEPLOYMENT_IDENTITY_FOR_AGENT AS
SELECT
  (SELECT PARAM_VALUE FROM SYS.EXA_METADATA WHERE PARAM_NAME = 'databaseName')
    AS DATABASE_NAME,
  (SELECT PARAM_VALUE FROM SYS.EXA_METADATA WHERE PARAM_NAME = 'databaseProductVersion')
    AS DATABASE_VERSION,
  (SELECT MAX(DISPLAY_VERSION) FROM SEMANTIC_CATALOG.PRODUCT_VERSION)
    AS PRODUCT_VERSION,
  (SELECT MAX(RUNTIME_CHECKSUM) FROM SEMANTIC_CATALOG.PRODUCT_VERSION)
    AS RUNTIME_CHECKSUM,
  (SELECT MAX(INSTALLED_AT) FROM SEMANTIC_CATALOG.PRODUCT_VERSION)
    AS INSTALLED_AT,
  (SELECT COUNT(*) FROM SEMANTIC_CATALOG.MODELS) AS MODEL_COUNT,
  CURRENT_USER AS CONNECTED_AS,
  CURRENT_SESSION AS SESSION_ID
FROM DUAL;

CREATE OR REPLACE VIEW SEMANTIC_AGENT.MODELS_FOR_AGENT AS
SELECT
  m.MODEL_ID,
  m.MODEL_NAME,
  m.PUBLISHED_SCHEMA,
  m.DESCRIPTION,
  m.OWNER_ROLE,
  m.STATUS AS MODEL_STATUS,
  m.ACTIVE_VERSION_ID AS VERSION_ID,
  mv.VERSION_NUMBER,
  m.PREPROCESSOR_SCHEMA,
  m.PREPROCESSOR_SCRIPT,
  m.PREPROCESSOR_SCHEMA || '.' || m.PREPROCESSOR_SCRIPT AS PREPROCESSOR_QUALIFIED_NAME,
  TRUE AS SESSION_SETUP_REQUIRED,
  'EXECUTE SCRIPT SEMANTIC_ADMIN.ENABLE_SEMANTIC_SQL()' AS SESSION_SETUP_SQL,
  m.SURFACE_TYPE,
  vr.VALIDATION_RUN_ID AS LATEST_VALIDATION_RUN_ID,
  vr.STATUS AS VALIDATION_STATUS,
  vr.ERROR_COUNT AS VALIDATION_ERROR_COUNT,
  COALESCE(pc.PRECONDITION_COUNT, 0) AS VALIDATION_PRECONDITION_COUNT,
  vr.WARNING_COUNT AS VALIDATION_WARNING_COUNT,
  CASE
    WHEN m.STATUS <> 'PUBLISHED' THEN 'NOT_PUBLISHED'
    WHEN vr.VALIDATION_RUN_ID IS NULL THEN 'NEEDS_VALIDATION'
    WHEN vr.ERROR_COUNT > 0 THEN 'INVALID'
    WHEN COALESCE(pc.PRECONDITION_COUNT, 0) > 0 THEN 'PRECONDITION'
    WHEN vr.WARNING_COUNT > 0 THEN 'WARNING'
    ELSE 'VALID'
  END AS AGENT_READINESS,
  'STRUCTURED_REQUEST,SEMANTIC_SQL' AS QUERY_MODES,
  -- A client pinned to a static host:port can reach a different deployment
  -- than intended and answer confidently from the wrong catalog. Carry the
  -- identity an agent can assert on the surface it already reads.
  (SELECT DATABASE_NAME FROM SEMANTIC_AGENT.DEPLOYMENT_IDENTITY_FOR_AGENT)
    AS DATABASE_NAME,
  (SELECT RUNTIME_CHECKSUM FROM SEMANTIC_AGENT.DEPLOYMENT_IDENTITY_FOR_AGENT)
    AS RUNTIME_CHECKSUM
FROM SEMANTIC_SOURCE.MODELS m
LEFT JOIN SEMANTIC_SOURCE.MODEL_VERSIONS mv
  ON mv.VERSION_ID = m.ACTIVE_VERSION_ID
LEFT JOIN (
  SELECT MODEL_ID, VERSION_ID, MAX(VALIDATION_RUN_ID) AS VALIDATION_RUN_ID
  FROM SEMANTIC_SOURCE.VALIDATION_RUNS
  GROUP BY MODEL_ID, VERSION_ID
) latest
  ON latest.MODEL_ID = m.MODEL_ID
 AND latest.VERSION_ID = m.ACTIVE_VERSION_ID
LEFT JOIN SEMANTIC_SOURCE.VALIDATION_RUNS vr
  ON vr.VALIDATION_RUN_ID = latest.VALIDATION_RUN_ID
LEFT JOIN (
  SELECT VALIDATION_RUN_ID, COUNT(*) AS PRECONDITION_COUNT
  FROM SEMANTIC_SOURCE.VALIDATION_RESULTS
  WHERE SEVERITY = 'PRECONDITION'
  GROUP BY VALIDATION_RUN_ID
) pc
  ON pc.VALIDATION_RUN_ID = vr.VALIDATION_RUN_ID
WHERE m.STATUS <> 'DELETED';

CREATE OR REPLACE VIEW SEMANTIC_AGENT.OBJECTS_FOR_AGENT AS
SELECT
  m.MODEL_ID,
  m.MODEL_NAME,
  m.VERSION_ID,
  m.VERSION_NUMBER,
  m.PUBLISHED_SCHEMA,
  so.OBJECT_ID,
  so.OBJECT_NAME,
  so.OBJECT_NAME AS PUBLISHED_OBJECT_NAME,
  UPPER(so.OBJECT_NAME) AS SQL_OBJECT_NAME,
  so.DESCRIPTION,
  so.ROOT_ENTITY_ID,
  re.ENTITY_NAME AS ROOT_ENTITY_NAME,
  so.STATUS AS OBJECT_STATUS,
  m.LATEST_VALIDATION_RUN_ID,
  m.VALIDATION_STATUS,
  m.AGENT_READINESS,
  m.PREPROCESSOR_QUALIFIED_NAME,
  m.QUERY_MODES,
  m.DATABASE_NAME,
  m.RUNTIME_CHECKSUM,
  -- Fusion is invisible on this surface unless it is said out loud: an agent
  -- reading only names cannot tell a single-source object from one whose
  -- numbers are merged across partitions or reconciled across systems.
  -- Summarised for the root entity, which is the grain the object's metrics
  -- are based on; SEMANTIC_AGENT.FUSION_FOR_AGENT has the declarations.
  (
    SELECT COUNT(*)
    FROM SEMANTIC_SOURCE.ENTITY_REPRESENTATIONS er
    WHERE er.ENTITY_ID = so.ROOT_ENTITY_ID
      AND er.VERSION_ID = so.VERSION_ID
      AND er.STATUS = 'ACTIVE'
  ) AS SOURCE_COUNT,
  COALESCE(
    (
      SELECT 'UNION'
      FROM SEMANTIC_SOURCE.ENTITY_REPRESENTATIONS er
      WHERE er.ENTITY_ID = so.ROOT_ENTITY_ID
        AND er.VERSION_ID = so.VERSION_ID
        AND er.STATUS = 'ACTIVE'
        AND er.COVERAGE_PREDICATE IS NOT NULL
      LIMIT 1
    ),
    (
      SELECT MAX(afp.FUSION_STRATEGY)
      FROM SEMANTIC_SOURCE.ATTRIBUTE_FUSION_POLICIES afp
      WHERE afp.ENTITY_ID = so.ROOT_ENTITY_ID
        AND afp.VERSION_ID = so.VERSION_ID
        AND afp.STATUS = 'ACTIVE'
        AND afp.FUSION_STRATEGY IN ('COALESCE', 'RECONCILE')
    ),
    'NONE'
  ) AS FUSION_STRATEGY
FROM SEMANTIC_AGENT.MODELS_FOR_AGENT m
JOIN SEMANTIC_SOURCE.SEMANTIC_OBJECTS so
  ON so.MODEL_ID = m.MODEL_ID
 AND so.VERSION_ID = m.VERSION_ID
LEFT JOIN SEMANTIC_SOURCE.ENTITIES re
  ON re.ENTITY_ID = so.ROOT_ENTITY_ID
-- What an agent may see is decided by what it may read: MODELS_FOR_AGENT is
-- reached through SEMANTIC_AGENT, and the published schema through Exasol's own
-- grants. There used to be a second, semantic-layer ACL here over
-- OBJECT_PRIVILEGES -- allow unless a grant exists, then allow only the
-- grantees. No script could ever write that table, so the first branch always
-- won and the whole clause meant TRUE. See 001 for why it is gone.
WHERE so.STATUS = 'ACTIVE';

